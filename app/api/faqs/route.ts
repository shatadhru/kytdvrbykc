export async function GET(req: NextRequest) {
  try {
    const { searchParams } = new URL(req.url)
    const homeOnly = searchParams.get('home') === 'true'

    const payload = await getPayload({ config })
    const whereConditions: any[] = [{ isActive: { equals: true } }]
    if (homeOnly) {
      whereConditions.push({ showOnHome: { equals: true } })
    }

    const faqsRes = await payload.find({
      collection: 'faqs' as any,
      where: {
        and: whereConditions,
      },
      sort: 'order',
      depth: 0,
      limit: 50,
      overrideAccess: true,
    })

    if (faqsRes.docs && faqsRes.docs.length > 0) {
      const faqs = faqsRes.docs.map((doc: any) => ({
        id: String(doc.id),
        question: doc.question,
        answer: doc.answer,
      }))
      return NextResponse.json({ success: true, faqs })
    }

    return NextResponse.json({ success: true, faqs: DEFAULT_FAQS })
  } catch (err: any) {
    console.warn('GET /api/faqs fallback to default:', err?.message)
    return NextResponse.json({ success: true, faqs: DEFAULT_FAQS })
  }
}
